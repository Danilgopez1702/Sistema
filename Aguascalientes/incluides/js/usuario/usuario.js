function editar(id_usuario,usuario_usuario,pass_usuario,tipo_usuario,status_usuario)
    {
    document.getElementById('editar_id_usuario').value = id_usuario;
    document.getElementById('editar_usuario').value = usuario_usuario;
    document.getElementById('editar_pass').value = pass_usuario;
    document.getElementById('editar_tipo').value = tipo_usuario;
    document.getElementById('editar_status').value = status_usuario;
    }