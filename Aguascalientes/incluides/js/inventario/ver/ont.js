function editar(id_inventario,ont_inventario,mac_ont_inventario,id_instalador,fallo_inventario)
    {
    document.getElementById('editar_id_inventario').value = id_inventario;
    document.getElementById('editar_onu_inventario').value = ont_inventario;
    document.getElementById('editar_mac_inventario').value = mac_ont_inventario;
    document.getElementById('editar_id_instalador').value = id_instalador;
    document.getElementById('editar_fallo_inventario').value = fallo_inventario;
    }